/* The FONT KIT (the owner, 2026-10-16; docs/LAYOUT.md §9): runtime/fontkit.json -> runtime/fontkit.tsx, Poppins carried INSIDE every tool
 * like the mascot, because staging and some devices have no Poppins and their text fell back to Segoe UI or the system font (not what
 * `check` renders). Each face (assets/fonts/*.ttf, SIL OFL 1.1, the licence beside them) is subset with fontTools to the plan's unicode
 * ranges (Latin, the rupee and the maths signs, Devanagari; Gujarati stays on the device's font) as woff2, and written as @font-face
 * rules with data URIs under a private family name. The runtime's FONT_KIT block puts them in its <style> and loads them on mount.
 * Needs python3 with fontTools and brotli. Never read runtime/fontkit.tsx; regenerate it.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fromRoot } from "../core/env.mjs";

export function makeFontKit({ log = console.log } = {}) {
  const plan = JSON.parse(fs.readFileSync(fromRoot("runtime/fontkit.json"), "utf8"));
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "c4fontkit-"));
  const rules = [], sizes = [];
  try {
    for (const f of plan.faces) {
      const src = fromRoot(f.file), out = path.join(tmp, `${f.weight}.woff2`);
      execFileSync("python3", ["-m", "fontTools.subset", src, `--unicodes=${plan.unicodes}`, "--flavor=woff2", "--layout-features=*", `--output-file=${out}`], { stdio: ["ignore", "ignore", "pipe"] });
      const b64 = fs.readFileSync(out).toString("base64");
      sizes.push({ weight: f.weight, woff2: fs.statSync(out).size, uri: b64.length });
      rules.push(`@font-face{font-family:'${plan.family}';font-style:normal;font-weight:${f.weight};font-display:${plan.display || "swap"};`
        + `src:url(data:font/woff2;base64,${b64}) format('woff2');unicode-range:${plan.unicodes}}`);
    }
  } finally { fs.rmSync(tmp, { recursive: true, force: true }); }
  const licence = fs.readFileSync(fromRoot(plan.licence), "utf8").split(/\r?\n/).find((l) => /copyright/i.test(l)) || "";
  const kit = { family: plan.family, weights: plan.faces.map((f) => f.weight), licence: `${licence.trim()}; SIL Open Font License 1.1`, css: rules.join("") };
  const out = fromRoot("runtime/fontkit.tsx");
  fs.writeFileSync(out, `/* GENERATED by \`node cli.mjs fontkit\` from runtime/fontkit.json: the FONT KIT (docs/LAYOUT.md §9), ${kit.family} ${kit.weights.join(", ")}
   as woff2 data URIs (${sizes.map((s) => `${s.weight}: ${(s.woff2 / 1024).toFixed(1)} KB`).join(", ")}). It travels inside every tool built on a runtime that has
   it, like the mascot. Poppins: SIL Open Font License 1.1 (assets/fonts/OFL.txt). Do not edit or read; regenerate. */
const FONT_KIT: any = ${JSON.stringify(kit)};
`);
  const bytes = fs.statSync(out).size;
  for (const s of sizes) log(`  ${kit.family} ${s.weight}  woff2 ${(s.woff2 / 1024).toFixed(1)} KB  (${(s.uri / 1024).toFixed(1)} KB base64)`);
  log(`  ${path.relative(process.cwd(), out)}: ${(bytes / 1024).toFixed(1)} KB in every tool built on it`);
  return { out, bytes, sizes };
}
