/* textbooks/mascot.png -> runtime/mascot.tsx: the footer mascot, carried INSIDE every tool.
 *
 * Nothing is fetched at run time, so the local preview, staging and production paint the
 * same bytes (the NCERT Class 4 tools ship their mascot the same way). The PNG is used as it
 * is: trimmed to the art, scaled to a height that stays sharp on a 2x smartboard, and encoded
 * as WebP by headless Chrome's own canvas, so there is no image dependency.
 * The output is a data URI of ~50 KB. Never read runtime/mascot.tsx; regenerate it.
 */
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { CONFIG, fromRoot } from "../core/env.mjs";
import { dumpDom } from "../core/chrome.mjs";

export function mascotSource() {
  return fromRoot(CONFIG.mascot || "../textbooks/mascot.png");
}

export function makeMascot({ src = mascotSource(), height = 420, quality = 0.86 } = {}) {
  if (!fs.existsSync(src)) throw new Error(`mascot image not found: ${src}`);
  const png = fs.readFileSync(src);
  if (png.readUInt32BE(0) !== 0x89504e47) throw new Error(`${src} is not a PNG`);
  const tmp = fromRoot(".build");
  fs.mkdirSync(tmp, { recursive: true });
  const page = path.join(tmp, "mascot.html");
  fs.writeFileSync(page, `<!doctype html><meta charset="utf-8"><body><pre id="out">pending</pre><script>
const img = new Image();
img.onerror = () => { document.getElementById("out").textContent = JSON.stringify({ error: "decode failed" }); };
img.onload = () => {
  const c = document.createElement("canvas"); c.width = img.naturalWidth; c.height = img.naturalHeight;
  const g = c.getContext("2d"); g.drawImage(img, 0, 0);
  const d = g.getImageData(0, 0, c.width, c.height).data;
  let x0 = c.width, y0 = c.height, x1 = -1, y1 = -1, clear = 0;
  for (let y = 0; y < c.height; y++) for (let x = 0; x < c.width; x++) {
    const a = d[(y * c.width + x) * 4 + 3];
    if (a < 250) clear++;
    if (a > 16) { if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y; }
  }
  const w = x1 - x0 + 1, h = y1 - y0 + 1, H = ${Number(height)}, Wd = Math.round((w * H) / h);
  const o = document.createElement("canvas"); o.width = Wd; o.height = H;
  const og = o.getContext("2d"); og.imageSmoothingEnabled = true; og.imageSmoothingQuality = "high";
  og.drawImage(c, x0, y0, w, h, 0, 0, Wd, H);
  document.getElementById("out").textContent = JSON.stringify({
    src: { w: c.width, h: c.height }, box: { x0, y0, w, h }, out: { w: Wd, h: H },
    transparent: clear / (c.width * c.height), webp: o.toDataURL("image/webp", ${Number(quality)}) });
};
img.src = "data:image/png;base64,${png.toString("base64")}";
</script>`);
  const dom = dumpDom(pathToFileURL(page).href, { budget: 5000, label: "mascot" });
  fs.rmSync(page, { force: true });
  const m = /<pre id="out">([\s\S]*?)<\/pre>/.exec(dom);
  if (!m) throw new Error("mascot page produced nothing");
  const r = JSON.parse(m[1].replace(/&quot;/g, '"').replace(/&amp;/g, "&"));
  if (r.error) throw new Error(`mascot: ${r.error}`);
  if (!/^data:image\/webp;base64,/.test(r.webp)) throw new Error("this Chrome did not encode WebP");
  if (r.transparent < 0.2) console.log("  warning: the mascot PNG has little transparency; it will paint its own background");
  const rel = path.relative(fromRoot("."), src).replace(/\\/g, "/");
  const out = fromRoot("runtime/mascot.tsx");
  fs.writeFileSync(out, `/* GENERATED by \`node cli.mjs mascot\` from ${rel} (${r.src.w}x${r.src.h}, art ${r.box.w}x${r.box.h})
   -> ${r.out.w}x${r.out.h} WebP q${quality}. The mascot travels inside the tool; nothing is fetched,
   so the preview, staging and production paint these exact bytes. Do not edit or read; regenerate. */
const MASCOT_IMAGE: string = "${r.webp}";
const MASCOT_SIZE = { w: ${r.out.w}, h: ${r.out.h} };
`);
  return { out, source: src, src: r.src, art: r.box, size: r.out, bytes: Buffer.byteLength(r.webp) };
}
